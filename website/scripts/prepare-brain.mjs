import {readFileSync, writeFileSync} from 'node:fs';
import {GLTFLoader} from 'three/addons/loaders/GLTFLoader.js';
import {MeshoptSimplifier} from 'meshoptimizer';
import {mergeGeometries, mergeVertices} from 'three/addons/utils/BufferGeometryUtils.js';
import {Box3, Vector3, Matrix4} from 'three';
const sourceUrl='https://raw.githubusercontent.com/hubmapconsortium/hra-kg/main/digital-objects/ref-organ/brain-male/v1.3/raw/3d-vh-m-allen-brain.glb';
const file=Buffer.from(await (await fetch(sourceUrl)).arrayBuffer());
const gltf=await new GLTFLoader().parseAsync(file.buffer.slice(file.byteOffset,file.byteOffset+file.byteLength),'');
gltf.scene.updateMatrixWorld(true);
const list=[];
gltf.scene.traverse(o=>{if(o.isMesh && !/optic_chiasm/.test(o.name)){const g=o.geometry.clone().applyMatrix4(o.matrixWorld);for(const name of Object.keys(g.attributes))if(!['position','normal'].includes(name))g.deleteAttribute(name);if(!g.attributes.normal)g.computeVertexNormals();list.push(g);}});
let merged=mergeGeometries(list);
merged=mergeVertices(merged, 0.0000005);
await MeshoptSimplifier.ready;
const [indices,error]=MeshoptSimplifier.simplifyWithAttributes(new Uint32Array(merged.index.array),merged.attributes.position.array,3,merged.attributes.normal.array,3,[.1,.1,.1],null,300000,.008);
merged.setIndex(Array.from(indices));
const [remap,count]=MeshoptSimplifier.compactMesh(indices);
const compact=new Float32Array(count*3);
const compactNormals=new Float32Array(count*3);
for(let old=0;old<remap.length;old++)if(remap[old]!==0xffffffff){compact.set(merged.attributes.position.array.subarray(old*3,old*3+3),remap[old]*3);compactNormals.set(merged.attributes.normal.array.subarray(old*3,old*3+3),remap[old]*3);}
import {Float32BufferAttribute} from 'three';
merged.setAttribute('position',new Float32BufferAttribute(compact,3));
merged.setIndex(Array.from(indices));
merged.setAttribute('normal',new Float32BufferAttribute(compactNormals,3));
merged.computeBoundingBox();
const center=merged.boundingBox.getCenter(new Vector3());
const size=merged.boundingBox.getSize(new Vector3());
merged.applyMatrix4(new Matrix4().makeTranslation(-center.x,-center.y,-center.z));
merged.scale(3.5/Math.max(size.x,size.y,size.z),3.5/Math.max(size.x,size.y,size.z),3.5/Math.max(size.x,size.y,size.z));
const positions=merged.attributes.position.array, normals=merged.attributes.normal.array;
// Half-float attributes keep the locally served model below 3MB. Loader uses Float16BufferAttribute.
import {DataUtils} from 'three';
const result=new Uint16Array(positions.length+normals.length);
for(let i=0;i<positions.length;i++)result[i]=DataUtils.toHalfFloat(positions[i]);
for(let i=0;i<normals.length;i++)result[positions.length+i]=DataUtils.toHalfFloat(normals[i]);
const packed=Buffer.concat([Buffer.from(result.buffer),Buffer.from(indices.buffer)]);
writeFileSync(new URL('../public/models/brain.bin',import.meta.url),packed);
writeFileSync(new URL('../public/models/brain.json',import.meta.url),JSON.stringify({vertices:positions.length/3,indices:indices.length,format:'float16-positions-then-normals',source:'HRA Brain, Male v1.3',license:'CC BY 4.0',originalBounds:size.toArray(),sourceUrl:'https://doi.org/10.48539/HBM929.XKCL.339'}));
console.log({sourceBytes:file.length,deliveryBytes:packed.byteLength,vertices:positions.length/3,bounds:size.toArray()});
